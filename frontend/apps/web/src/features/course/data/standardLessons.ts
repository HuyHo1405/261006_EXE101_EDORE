export interface ChapterInfo {
  id: string;
  title: string;
  order: number;
  gradeCode: string;
  subjectCode: string;
  semester?: 1 | 2;
}

export function getSemesterForChapter(
  gradeCode?: string,
  chapterOrderOrTitle?: string | number
): 1 | 2 {
  if (typeof chapterOrderOrTitle === "number") {
    const cleanGrade = (gradeCode || "").replace(/\D+/g, "");
    if (cleanGrade === "6" || cleanGrade === "7") {
      return chapterOrderOrTitle <= 3 ? 1 : 2;
    }
    return chapterOrderOrTitle <= 2 ? 1 : 2;
  }
  if (typeof chapterOrderOrTitle === "string") {
    const match = chapterOrderOrTitle.match(/chương\s*(\d+)/i);
    if (match) {
      const num = parseInt(match[1], 10);
      const cleanGrade = (gradeCode || "").replace(/\D+/g, "");
      if (cleanGrade === "6" || cleanGrade === "7") {
        return num <= 3 ? 1 : 2;
      }
      return num <= 2 ? 1 : 2;
    }
  }
  return 1;
}

