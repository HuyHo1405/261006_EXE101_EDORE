"""Validate leader's workbook and generate repeatable PostgreSQL question-bank SQL.

Requires openpyxl. Does not connect to or mutate a database.
"""
import argparse
from pathlib import Path
import openpyxl


def quote(value):
    return "NULL" if value is None else "'" + str(value).replace("'", "''") + "'"


def load_questions(path):
    workbook = openpyxl.load_workbook(path, read_only=True, data_only=True)
    try:
        rows = iter(workbook['lesson_questions'].values)
        headers = next(rows)
        questions = []
        ids = set()
        for line, row in enumerate(rows, 2):
            q = dict(zip(headers, row))
            if not q.get('question'):
                continue
            for field in ('question_id', 'lesson_code', 'answer_1', 'answer_2'):
                if not q.get(field):
                    raise ValueError(f'Row {line}: missing {field}')
            if q['question_id'] in ids:
                raise ValueError(f'Row {line}: duplicate question_id')
            ids.add(q['question_id'])
            correct = q.get('correct_answer')
            if correct not in (1, 2, 3, 4) or not q.get(f'answer_{int(correct)}'):
                raise ValueError(f'Row {line}: invalid correct_answer')
            if q.get('stage_tag') not in ('PRACTICE', 'WARM_UP'):
                raise ValueError(f'Row {line}: invalid stage_tag')
            if q.get('difficulty') not in ('EASY', 'MEDIUM', 'HARD'):
                raise ValueError(f'Row {line}: invalid difficulty')
            if q.get('time_limit') not in (5, 10, 20, 30, 60, 120):
                raise ValueError(f'Row {line}: invalid time_limit')
            questions.append(q)
        if not questions:
            raise ValueError('No questions found')
        return questions
    finally:
        workbook.close()


def generate_sql(questions):
    columns = ('id', 'lesson_id', 'lesson_code', 'question_text', 'option_1', 'option_2',
               'option_3', 'option_4', 'correct_answer', 'time_limit', 'stage_tag', 'difficulty', 'explanation')
    statements = ['-- Generated by scripts/import_lesson_questions.py; import lessons first.', 'BEGIN;',
                  '''CREATE TABLE IF NOT EXISTS lesson_question (
id varchar(255) PRIMARY KEY, lesson_id varchar(255), lesson_code varchar(255),
question_text text, option_1 text, option_2 text, option_3 text, option_4 text,
correct_answer integer, time_limit integer, stage_tag varchar(255), difficulty varchar(255), explanation text
);
CREATE INDEX IF NOT EXISTS idx_question_lesson_stage ON lesson_question (lesson_code, stage_tag);''',
                  f'''DO $$ BEGIN
IF EXISTS (SELECT code FROM (VALUES {', '.join('(' + quote(c) + ')' for c in sorted({q['lesson_code'] for q in questions}))}) AS source(code)
WHERE (SELECT count(*) FROM lesson_metadata m WHERE m.code = source.code) <> 1)
THEN RAISE EXCEPTION 'Every question lesson_code must match exactly one lesson_metadata row. Import the supplied lesson data first.';
END IF; END; $$;''']
    for q in questions:
        values = [quote(q['question_id']), '(SELECT id FROM lesson_metadata WHERE code = ' + quote(q['lesson_code']) + ')',
                  quote(q['lesson_code']), quote(q['question'])]
        values += [quote(q.get(f'answer_{i}')) for i in range(1, 5)]
        values += [str(int(q['correct_answer'])), str(int(q['time_limit'])), quote(q['stage_tag']),
                   quote(q['difficulty']), quote(q.get('explanation'))]
        statements.append(f"INSERT INTO lesson_question ({', '.join(columns)}) VALUES ({', '.join(values)}) "
                          + 'ON CONFLICT (id) DO UPDATE SET '
                          + ', '.join(f'{c} = EXCLUDED.{c}' for c in columns[1:]) + ';')
    statements.append('COMMIT;')
    return '\n'.join(statements) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('workbook', type=Path)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'java-backend/lesson-questions-generated.sql')
    args = parser.parse_args()
    questions = load_questions(args.workbook)
    args.output.write_text(generate_sql(questions), encoding='utf-8')
    print(f'Validated {len(questions)} questions; SQL saved to {args.output}')


if __name__ == '__main__':
    main()
